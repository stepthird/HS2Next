        /// <summary>
        /// The sections of one accessory with concrete paths under
        /// `appearance.coord.accessories["&lt;id&gt;"].`, for the slot group of build slot <paramref name="slot"/> (0-based; the section
        /// ids carry its two-digit number, the gates its digits) whose accessory is of <paramref name="category"/> (351..363: the
        /// item list's category for both sexes; the page rebuilds the group when the category changes). In HS2's tab order:
        /// Type (the 14 type choices — «なし» removes —, the item list), Colour (normal rows: colours 1–3 without alpha and colour
        /// 4 of the alpha renderers with alpha, «ツヤ» / «質感» of each, «初期カラー»), Hair colour (hair-type rows: «基本カラー»,
        /// «根本カラー», «毛先カラー», «ツヤカラー», «質感», «滑らかさ», «髪の毛の色を取得» × 4), Parent (the attach point picker, «初期親»;
        /// the head-weighted note under `…:head`), Adjust («揺らさない», per transform set c the position / rotation / scale rows
        /// and «初期化»). Rows the prefab does not use are gated (maker.acc:&lt;slot&gt;:&lt;feature&gt;). Sliders follow the Maker rule
        /// (drag 0..1, typed −1..2, shown × 100, stored unclamped); ↺ of gloss / metallic = the worn prefab's default, of the hair
        /// sliders and the colours the reference, of a transform component its constant (0, 0, 1). Values: "Edit accessory";
        /// the type and the item: "Change item".
        /// </summary>
        public static IReadOnlyList<SchemaSection> AccessoryRows(string accessoryId, int slot, int category)
        {
            var list = new List<SchemaSection>();
            string P(string member) => AccessoryEditPath(accessoryId, member);
            string G(string feature) => SchemaGates.MakerAcc(slot, feature);
            var watch = new[] { P("item"), P("category") };

            // Type: the 14 types (values 350..363) and the item list of the accessory's category
            var sec = AccessorySection(list, AccessorySectionId(slot, "type"), "type", out var b);
            sec.Watch = watch;
            var type = b.Enum(P("category"), "type", StringArray(AccessoryTypeNames), AccessoryLabels + "type.");
            type.ChoiceValues = TypeValues;
            type.Whole = true;
            type.OpLabel = OpLabels.ChangeItem;
            b.Add(new FieldSpec
            {
                Path = P("item"), Kind = FieldKind.PartList, LabelKey = AccessoryLabels + "item", CategoryFemale = category, CategoryMale = category,
                OpLabel = OpLabels.ChangeItem, ListContext = FieldSpec.ListContextAccessory,
            });

            // Colour (normal rows): areas 1–3 without alpha, colour 4 (alpha renderers) with alpha
            sec = AccessorySection(list, AccessorySectionId(slot, "colour"), "colour", out b);
            sec.Gate = G(SchemaGates.AccColour);
            sec.Watch = new[] { P("item"), P("category"), CharaEditPath("hair.shaderType") };
            for (int n = 1; n <= 4; n++)
            {
                string gate = n <= 3 ? G(SchemaGates.AccArea(n)) : G(SchemaGates.AccAlpha);
                string c = "colors[" + (n - 1) + "].";
                var col = b.Color(P(c + "color"), "colour" + n, n == 4, new[] { 1.0, 1.0, 1.0, 1.0 });
                col.Gate = gate;
                var gloss = AccessorySlider(b, P(c + "gloss"), "gloss", 0.5);
                gloss.Gate = gate;
                gloss.ResetKind = ResetKind.PrefabDefault;
                var metallic = AccessorySlider(b, P(c + "metallic"), "metallic", 0.5);
                metallic.Gate = gate;
                metallic.ResetKind = ResetKind.PrefabDefault;
            }
            b.Button(ActionResetAccessoryColours(accessoryId), "defaultColours").Gate = G(SchemaGates.AccColour);

            // Hair colour (hair-type rows)
            sec = AccessorySection(list, AccessorySectionId(slot, "hairColour"), "hairColour", out b);
            sec.Gate = G(SchemaGates.AccHair);
            sec.Watch = new[] { P("item"), P("category"), CharaEditPath("hair.shaderType") };
            b.Color(P("colors[0].color"), "hairBase", false, new[] { 1.0, 1.0, 1.0, 1.0 }).Gate = G(SchemaGates.AccHair);
            b.Color(P("colors[1].color"), "hairTop", false, new[] { 1.0, 1.0, 1.0, 1.0 }).Gate = G(SchemaGates.AccTop);
            b.Color(P("colors[2].color"), "hairUnder", false, new[] { 1.0, 1.0, 1.0, 1.0 }).Gate = G(SchemaGates.AccUnder);
            b.Color(P("colors[3].color"), "hairSpecular", false, new[] { 1.0, 1.0, 1.0, 1.0 }).Gate = G(SchemaGates.AccHair);
            AccessorySlider(b, P("colors[0].metallic"), "hairMetallic", 0.5).Gate = G(SchemaGates.AccHair);
            AccessorySlider(b, P("colors[0].smoothness"), "hairSmoothness", 0.5).Gate = G(SchemaGates.AccHair);
            for (int k = 0; k < HairParts.Count; k++)
                b.Button(ActionMatchAccessoryHairColour(k, accessoryId), "hairFetch." + HairParts[k]).Gate = G(SchemaGates.AccHair);

            // Parent: the 54 attach points («初期親» after them); a fixed row ("0") gates the section off
            sec = AccessorySection(list, AccessorySectionId(slot, "parent"), "parent", out b);
            sec.Gate = G(SchemaGates.AccParent);
            sec.Watch = watch;
            b.Add(new FieldSpec { Path = P("parent"), Kind = FieldKind.AttachPoint, LabelKey = AccessoryLabels + "parent", Default = "", Gate = G(SchemaGates.AccParent) });
            b.Button(ActionResetAccessoryParent(accessoryId), "defaultParent").Gate = G(SchemaGates.AccParent);

            // Adjust: «揺らさない», then per transform set the three vector rows (stored units, HS2's grids) and «初期化»
            sec = AccessorySection(list, AccessorySectionId(slot, "adjust"), "adjust", out b);
            sec.Watch = watch;
            var ns = b.Bool(P("noShake"), "noShake");
            ns.Default = false;
            for (int c = 1; c <= 2; c++)
            {
                string m = "moves[" + (c - 1) + "].";
                string gate = G(SchemaGates.AccMove(c));
                var pos = b.Vec3(P(m + "position"), "position", new[] { 0.0, 0.0, 0.0 });
                pos.Gate = gate;
                pos.TypedMin = -AccessoryPositionLimit;
                pos.TypedMax = AccessoryPositionLimit;
                pos.Grid = AccessoryPositionGrid;
                pos.Format = "0.0";
                pos.ResetKind = ResetKind.Constant;
                var rot = b.Vec3(P(m + "rotation"), "rotation", new[] { 0.0, 0.0, 0.0 });
                rot.Gate = gate;
                rot.TypedMin = 0;
                rot.TypedMax = 360;
                rot.Grid = AccessoryRotationGrid;
                rot.GridTruncate = true;
                rot.Wrap360 = true;
                rot.Format = "0.#";
                rot.ResetKind = ResetKind.Constant;
                var scl = b.Vec3(P(m + "scale"), "scale", new[] { 1.0, 1.0, 1.0 });
                scl.Gate = gate;
                scl.TypedMin = AccessoryScaleMin;
                scl.TypedMax = AccessoryScaleMax;
                scl.Grid = AccessoryScaleGrid;
                scl.Format = "0.00";
                scl.ResetKind = ResetKind.Constant;
                b.Button(ActionResetAccessoryMove(c, accessoryId), "resetMove").Gate = gate;
            }
            return list;
        }

