        /// <summary>A Maker slider (Q23 ranges, × 100); <paramref name="component"/> ≥ 0 edits one component of a vector member.</summary>
        static FieldSpec Slider(B b, string member, string name, double def, bool lerp, int component = -1)
        {
            var f = b.Float(CharaEditPath(member), name, 0, 1, def, MakerTypedMin, MakerTypedMax);
            f.Scale = MakerSliderScale;
            f.Format = "0";
            f.Component = component;
            f.LerpClamped = lerp;
            return f;
        }

        /// <summary>The four component sliders of a layout vector (x, y, z, w).</summary>
        static void Layout(B b, string member, string[] names, double[] defs)
        {
            for (int c = 0; c < 4; c++) Slider(b, member, names[c], defs[c], true, c);
        }

