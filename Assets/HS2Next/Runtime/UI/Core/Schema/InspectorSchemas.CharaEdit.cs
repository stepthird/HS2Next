// The character inspector's Edit tab (tree; face pages of
// 1): the section tree Face / Body / Hair / Clothes / Accessories / Character / File,
// and the rows of the Face node's pages (4.0: Face › Shape; 4.1: Head & skin, Eyebrows, Eyes, Eyelashes, Makeup, Paint,
// Mole, Beard) and the Body node's (4.2, Shape, Skin, Tan, Nipples, Underhair,
// Nails, Paint, Special) and the Hair node's one page (4.3, options, the part
// selector, per part Style, Colour, Decoration, Bundles, Mesh; section ids "hair.hair.<part>.<section>", the part groups generated
// with concrete paths, prefab-dependent rows gated by "maker.hair:<part>:<feature>", sections naming their watched paths) and
// the Clothes node's one page (4.4: the kind selector, per kind Type, Colour 1–3 and Other with concrete paths under
// `appearance.coord.clothes.<kind>.`, rows gated by "maker.clothes:<kind>:<feature>", then the coordinate load button) and the
// Accessories node's one page (4.5: the slot list, per accessory Type, Colour or Hair colour, Parent and Adjust generated by
// AccessoryRows with concrete paths under `appearance.coord.accessories["<id>"].`, rows gated by "maker.acc:<slot>:<feature>",
// then the Copy section), the Character node's page (4.6: the name and the read-only lines of sex, futanari, the imported
// game parameters and the import provenance) and the File node's page (4.6: character save with the thumbnail framing and
// preview, character load with the five load flags, coordinate save and load).
// Section ids are "<tree node>.<page>.<section>" (4.0's "face.shape.chin" = node face, page shape; the rest may hold a dot). Rows address
// the character documents (`appearance.chara.face.…`, FieldAccessor's appearance root) and follow Q23: sliders 0..1
// shown 0–100 (FieldSpec.Scale 100), typed −100..200 (stored −1..2), stored unclamped; vector members are one row per
// component (FieldSpec.Component on the vector path); `Default` = the document default (colours as
// double[4] r, g, b, a; component rows the component's value) — the ↺ of a row resets to the reference value (
// StudioOps.ResetAppearance), the default is its fallback. Templates: {side} (left / right, the Eyes page's side selector)
// and {k} (face / body paint 0 / 1, the repeated sections `face.paint.p{k}` / `body.paint.p{k}`). Item rows are
// FieldKind.PartList (list category per sex), pushes FieldKind.Push (face presets, layout pushes, the skin colour swatches).
// Not part of AllSections (the 3.5 schema test resolves rows on nodes without documents and holds the HS2 range table of
// the Studio inspector); SchemaTests_CharaEdit / SchemaTests_CharaEditFace / SchemaTests_CharaEditBody check these
// tables. Unity-free.
