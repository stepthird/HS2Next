        static List<SchemaSection> BuildCharaEdit()
        {
            var list = new List<SchemaSection>();
            FaceHead(list);
            foreach (var (page, first, count) in FaceShapePages)
            {
                var sec = new SchemaSection("face.shape." + page, "inspector.charaEdit.page.face.shape." + page);
                var b = new B(sec, "inspector.charaEdit.face.shape.", OpLabels.EditFace);
                for (int i = first; i < first + count; i++)
                {
                    var f = b.Float(CharaEditPath("face.shape[" + i + "]"), FaceShapeNames[i], 0, 1, 0.5, MakerTypedMin, MakerTypedMax);
                    f.Scale = MakerSliderScale;
                    f.Format = "0";
                }
                list.Add(sec);
            }
            FaceEyebrow(list);
            FaceEyes(list);
            FaceEyelashes(list);
            FaceMakeup(list);
            FacePaint(list);
            FaceMole(list);
            FaceBeard(list);
            BodyShape(list);
            BodySkin(list);
            BodyDetails(list);
            BodyPaint(list);
            BodySpecial(list);
            Hair(list);
            Clothes(list);
            Accessories(list);
            CharacterNode(list);
            FileNode(list);
            return list;
        }

