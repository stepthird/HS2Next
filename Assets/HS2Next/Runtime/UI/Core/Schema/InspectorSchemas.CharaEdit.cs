        public static string ActionResetAccessoryColours(string accessoryId) => ActionResetAccessoryColoursPrefix + accessoryId;
        public static string ActionMatchAccessoryHairColour(int part, string accessoryId) => ActionMatchAccessoryHairColourPrefix + HairParts[part] + ":" + accessoryId;
        public static string ActionResetAccessoryParent(string accessoryId) => ActionResetAccessoryParentPrefix + accessoryId;
        public static string ActionResetAccessoryMove(int set, string accessoryId) =>
            ActionResetAccessoryMovePrefix + set.ToString(System.Globalization.CultureInfo.InvariantCulture) + ":" + accessoryId;

        /// <summary>The accessory id of a slot-group action with <paramref name="prefix"/> (for the hair colour fetch and the set
        /// reset the text after the part / set and ':'), or null; <paramref name="arg"/> = the part (0..3) or the set (1, 2), else -1.</summary>
        public static string AccessoryIdOfAction(string action, string prefix, out int arg)
        {
            arg = -1;
            if (action == null || prefix == null || !action.StartsWith(prefix, System.StringComparison.Ordinal)) return null;
            string rest = action.Substring(prefix.Length);
            if (prefix == ActionMatchAccessoryHairColourPrefix || prefix == ActionResetAccessoryMovePrefix)
            {
                int colon = rest.IndexOf(':');
                if (colon < 0) return null;
                string a = rest.Substring(0, colon);
                if (prefix == ActionMatchAccessoryHairColourPrefix) { for (int k = 0; k < HairParts.Count; k++) if (HairParts[k] == a) arg = k; }
                else if (a == "1" || a == "2") arg = a[0] - '0';
                if (arg < 0) return null;
                rest = rest.Substring(colon + 1);
            }
            return rest.Length > 0 ? rest : null;
        }

