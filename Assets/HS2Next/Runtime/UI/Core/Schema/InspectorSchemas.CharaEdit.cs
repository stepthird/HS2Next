        /// <summary>The tree node of an Edit tab section ("face.shape.chin" → "face").</summary>
        public static string CharaEditTreeOf(SchemaSection s)
        {
            int dot = s?.Id?.IndexOf('.') ?? -1;
            return dot < 0 ? s?.Id : s.Id.Substring(0, dot);
        }

        /// <summary>The page of an Edit tab section id ("face.shape.chin" → "shape", "face.paint.p{k}" → "paint"), or null.</summary>
        public static string CharaEditPageOf(string sectionId)
        {
            if (sectionId == null) return null;
            int a = sectionId.IndexOf('.');
            if (a < 0) return null;
            int b = sectionId.IndexOf('.', a + 1);
            return b < 0 ? sectionId.Substring(a + 1) : sectionId.Substring(a + 1, b - a - 1);
        }

        public static string CharaEditPageOf(SchemaSection s) => CharaEditPageOf(s?.Id);

        /// <summary>The pages of a tree node in order (the Face node: <see cref="FacePages"/>; the Body node: <see cref="BodyPages"/>;
        /// others: those their sections name).</summary>
        public static IReadOnlyList<string> CharaEditPagesOf(string node)
        {
            if (node == "face") return FacePages;
            if (node == "body") return BodyPages;
            if (node == "hair") return HairPages;
            if (node == "clothes") return ClothesPages;
            if (node == "accessories") return AccessoriesPages;
            var l = new List<string>();
            foreach (var s in CharaEdit)
                if (CharaEditTreeOf(s) == node) { var p = CharaEditPageOf(s); if (p != null && !l.Contains(p)) l.Add(p); }
            return l;
        }

